'use strict';
const assert=require('node:assert/strict'),M=require('../src/inspection_console/results_model.js');
const image=n=>String(n).repeat(64)+'.jpg',stamp=n=>'2026-10-24T11:0'+n+':00+00:00';
const result=(id,n)=>({instrument_id:id,status:'captured',image:image(n),image_sha256:String(n).repeat(64),
  captured_at:stamp(n),bbox:[100,200,200,300],image_status:'software_preset_fresh_reference_checked',quality:{accepted:true}});
const round=(id,n,results,status='completed')=>({id,map_id:'m',mode:'software_preset_capture',started_at:stamp(n),status,route:['A','B','C'],results});
const base={schedule:{enabled:false},instruments:['A','B','C'].map(id=>({id,map_id:'m',name:'表 '+id,enabled:true})),jobs:[
  {id:'commission',map_id:'m',mode:'annotation_commissioning',started_at:stamp(0),status:'completed',results:[]},
  round('r1',1,['A','B','C'].map(id=>result(id,1))),round('r2',2,[result('A',2)],'running')]};
const frozen=JSON.stringify(base),v=M.build(base,'m');
assert.equal(v.rounds.length,2);assert.equal(v.current.number,2);assert.equal(v.completed,1);
assert.deepEqual(v.rows.map(r=>r.kind),['current','previous','previous']);
assert.equal(v.rows[1].photo.capturedAt,stamp(1));assert.equal(v.rows[1].sourceRound,1);
assert.equal(v.rows[0].failed,false);
assert.equal(JSON.stringify(base),frozen,'fallback is a view, never a persisted capture');
let s=structuredClone(base);s.jobs[2].results.push({...result('B',2),status:'uncertain',image_status:'software_preset_uncertain_diagnostic'});
let model=M.build(s,'m');assert(model.rows[1].failed);assert.equal(model.rows[1].kind,'previous');assert.equal(model.completed,1);
assert.equal(M.historyRows({...model.current,job:{...model.current.job,status:'completed_with_errors'}},model.assets)[1].photo,null,'history never fills a failed round with an older image');
s.jobs[2].progress_results=[{...result('C',2),pending_round_completion:true}];model=M.build(s,'m');
assert.equal(model.rows[2].kind,'provisional');assert.equal(model.completed,1);assert.equal(model.previews,1);
s.jobs[2].status='failed';s.jobs[2].error='STOP_unconfirmed';model=M.build(s,'m');
assert.equal(model.completed,0);assert(model.rows.every(r=>r.kind==='previous'),'unconfirmed STOP cannot promote previews/final image to accepted');
s=structuredClone(base);s.jobs[2].status='completed';s.schedule={enabled:true,map_id:'m',batch_id:'new'};
model=M.build(s,'m');assert.equal(model.current.job,null);assert.equal(model.current.number,3);assert.equal(model.completed,0);
assert(model.rows.every(r=>r.kind==='previous'),'new armed batch must not label old results as new');
s=structuredClone(base);s.jobs[2].route.push('D');s.instruments.push({id:'D',map_id:'m',name:'新增表',enabled:true});
assert.equal(M.build(s,'m').rows[3].kind,'empty');
assert.equal(M.build({...base,jobs:[base.jobs[0]]},'m').rounds.length,0,'commissioning does not become round one');
const p=result('A',2);p.evidence={bbox:[1,1,4,4],image_sha256:'9'.repeat(64)};delete p.bbox;
assert.equal(M.photo(p).bbox,null,'cannot borrow bbox from another photograph');
p.crop_image=image(3);p.crop_sha256='3'.repeat(64);p.crop_source_sha256='2'.repeat(64);assert(M.photo(p).nativeCrop);
p.crop_source_sha256='4'.repeat(64);assert(!M.photo(p).nativeCrop);
assert.equal(M.photo({...p,image:'../../outside.jpg'}),null);
assert.deepEqual(M.cropRect([5,6,100,200],90,150,0),{x:5,y:6,width:85,height:144});
assert.equal(M.cropRect([100,100,120,120],80,80),null);
assert.equal(M.dateKey('2026-10-23T18:30:00Z'),'2026-10-24','date filter uses Shanghai time');
const archived=round('older',0,[result('A',1)]),stale=round('r2',2,[]);
model=M.build(base,'m',[archived,stale]);assert.equal(model.current.number,3);assert.equal(model.completed,1,'live records override archived snapshots');
s=structuredClone(base);s.instruments[1].name='<自定义名称>';model=M.build(s,'m');
assert.equal(model.rows[1].name,'<自定义名称>');assert.equal(model.rows[1].photo.capturedAt,stamp(1));
assert.equal(M.build(base,'different').rows.length,0,'scene results cannot leak across maps');
s=structuredClone(base);s.jobs[2].route=['C','B','A'];
assert.deepEqual(M.build(s,'m').rows.map(r=>r.id),['A','B','C'],'card order is independent of the optimized route');
model=M.build(s,'m');
assert.deepEqual(M.historyRows(model.current,model.assets).map(r=>r.id),['A','B','C'],'history keeps the same registry order');
assert.deepEqual(s.jobs[2].route,['C','B','A'],'display sorting must not change the physical route');
const maps=[{id:'old',title:'原场景',created_at:'2026-10-23T18:00:00Z'},{id:'m',title:'新场景',created_at:stamp(2)}];
const memory=new Map(),storage={getItem:k=>memory.get(k),setItem:(k,v)=>memory.set(k,v)};
let choice=M.sceneSelection(storage);
assert.equal(choice.resolve(maps,null,null),'m','first visit uses latest scene');
choice.remember('old');choice=M.sceneSelection(storage);
assert.equal(choice.resolve(maps,null,null),'old','refresh must reopen the chosen old scene');
assert.equal(choice.resolve([...maps,{id:'newer'}],'old',null),'old','a new scene must not steal explicit browsing');
assert.equal(choice.resolve(maps,'old','m'),'m','only an explicitly followed scan changes the selected scene');
assert.equal(choice.resolve(maps,null,'missing'),'m','stale preferred IDs do not erase saved selection');
choice.remember('removed');assert.equal(choice.resolve(maps,null,null),'m','removed scene falls back safely');
assert.equal(choice.resolve([],null,null),null);
const denied=M.sceneSelection({getItem(){throw Error('denied');},setItem(){throw Error('quota');}});
assert.equal(denied.resolve(maps,null,null),'m','blocked browser storage cannot break the workbench');
assert.equal(denied.resolve(maps,'old',null),'old');
s=structuredClone(base);s.maps=maps;s.instruments.push({id:'OLD',map_id:'old',name:'原表',enabled:true});
s.jobs=[];const oldJob={...round('old-round',1,[result('OLD',1)]),map_id:'old',route:['OLD']};
const sceneRows=M.scenes(s,[oldJob]);assert.equal(sceneRows[0].rounds,1);assert.equal(sceneRows[1].rounds,0);
assert(sceneRows[0].label.includes('2026/10/24'),'scene labels use Shanghai date');
assert.equal(M.build(s,'old',[oldJob]).rows[0].name,'原表');
assert.equal(M.build(s,'m',[oldJob]).completed,0,'new scenes cannot inherit an old instrument photo or success');
